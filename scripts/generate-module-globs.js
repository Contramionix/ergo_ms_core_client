/**
 * Генерирует sharedGlobs.generated.js с literal import.meta.glob для Vite.
 * Учитывает DISABLED_MODULES из корневого .env — отключённые модули не попадают в сборку.
 *
 * Режим wildcard (DISABLED_MODULES пуст): один glob на тип файлов — быстрее dev/build.
 * Режим per-module (DISABLED_MODULES непуст): отдельный glob на каждый enabled-модуль.
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'node:url'
import { loadDisabledModules, listEnabledModuleNames, clientProjectRoot } from './lib/parse-disabled-modules.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const clientRoot = path.resolve(__dirname, '..')
const modulesRoot = path.resolve(clientRoot, '../../modules')
const outputPath = path.join(clientRoot, 'src/modules/core/sharedGlobs.generated.js')

const envFileArg = process.argv.find((arg) => arg.startsWith('--env-file='))
const envPath = envFileArg
  ? path.resolve(envFileArg.slice('--env-file='.length))
  : path.join(clientProjectRoot, '.env')

const disabledModules = loadDisabledModules(envPath)
const enabledModules = listEnabledModuleNames(modulesRoot, disabledModules)
const usePerModuleGlobs = disabledModules.size > 0
const globMode = usePerModuleGlobs ? 'per-module' : 'wildcard'

const MODULES_GLOB_PREFIX = '../../../../../modules'

/**
 * @param {string} moduleName
 * @param {string} globPath — путь от modules/<name>/
 */
function moduleGlobLine(moduleName, globPath) {
  const normalized = globPath.replace(/\\/g, '/')
  return `  ...import.meta.glob('${MODULES_GLOB_PREFIX}/${moduleName}/${normalized}'),`
}

function buildPerModuleGlobBlock(globPath) {
  if (!enabledModules.length) {
    return '{}'
  }

  const lines = enabledModules.map((name) => moduleGlobLine(name, globPath))
  return `{\n${lines.join('\n')}\n}`
}

/**
 * @param {string} globPath — путь от modules/<name>/
 */
function buildWildcardGlobExport(globPath) {
  const normalized = globPath.replace(/\\/g, '/')
  return `import.meta.glob('${MODULES_GLOB_PREFIX}/*/${normalized}')`
}

/**
 * @param {string} globPath — путь от modules/<name>/
 */
function buildModuleGlobExport(globPath) {
  if (usePerModuleGlobs) {
    return buildPerModuleGlobBlock(globPath)
  }
  return buildWildcardGlobExport(globPath)
}

const content = `/**
 * AUTO-GENERATED by scripts/generate-module-globs.js — do not edit.
 * Glob mode: ${globMode}
 * Disabled modules (${disabledModules.size}): ${[...disabledModules].join(', ') || 'none'}
 * Enabled modules with client (${enabledModules.length}): ${enabledModules.join(', ') || 'none'}
 */

export const coreRoutes = import.meta.glob('../../core/**/js/routes.js')
export const coreEndpoints = import.meta.glob('../../core/**/js/endpoints.js')
export const corePermissionRules = import.meta.glob('../../core/**/js/permission-rules.js')
export const corePermissionSections = import.meta.glob('../../core/**/js/permission-sections.js')
export const coreRouteGuards = import.meta.glob('../../core/**/js/routeGuard.js')
export const coreIntegrations = import.meta.glob('../../core/**/js/integrations.js')
export const coreComponents = import.meta.glob('../../**/*.vue')

export const modulesRoutes = ${buildModuleGlobExport('client/js/routes.js')}
export const modulesRoutesNested = ${buildModuleGlobExport('client/**/js/routes.js')}
export const modulesEndpoints = ${buildModuleGlobExport('client/js/endpoints.js')}
export const modulesPermissionRules = ${buildModuleGlobExport('client/js/permission-rules.js')}
export const modulesPermissionSections = ${buildModuleGlobExport('client/js/permission-sections.js')}
export const modulesPermissionSectionsNested = ${buildModuleGlobExport('client/**/js/permission-sections.js')}
export const modulesRouteGuards = ${buildModuleGlobExport('client/js/routeGuard.js')}
export const modulesIntegrations = ${buildModuleGlobExport('client/js/integrations.js')}
export const modulesIntegrationsNested = ${buildModuleGlobExport('client/**/js/integrations.js')}
export const modulesThemeDefaults = ${buildModuleGlobExport('client/js/theme-defaults.js')}
export const modulesComponents = ${buildModuleGlobExport('client/**/*.vue')}
`

fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, content, 'utf8')

if (usePerModuleGlobs) {
  console.log(
    `[OK] sharedGlobs.generated.js: mode=per-module, ${enabledModules.length} enabled, ${disabledModules.size} disabled module(s)`,
  )
} else {
  console.log(
    `[OK] sharedGlobs.generated.js: mode=wildcard, ${enabledModules.length} module(s)`,
  )
}
