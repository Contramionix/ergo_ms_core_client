/**
 * Генерирует federation-entry, если в модуле нет своего client/federation-entry.js.
 * Хуки — стандартные файлы client/js/; страницы подхватываются glob'ом.
 * Импорт пишется ровно в ту форму, которую файл реально экспортирует.
 */

import fs from 'fs'
import path from 'path'
import { scanModuleExports } from './scan-module-exports.js'

const HOOKS = [
  ['routes', 'js/routes.js'],
  ['endpoints', 'js/endpoints.js'],
  ['permissionRules', 'js/permission-rules.js'],
  ['permissionSections', 'js/permission-sections.js'],
  ['routeGuard', 'js/routeGuard.js'],
  ['integrations', 'js/integrations.js'],
  ['locales', 'js/locales.js'],
  ['themeDefaults', 'js/theme-defaults.js'],
]

const GENERATED_NAME = '.federation-entry.generated.js'

export function generatedFederationEntryPath(moduleClientRoot) {
  return path.join(moduleClientRoot, GENERATED_NAME)
}

/**
 * @param {string} key
 * @param {string} rel
 * @param {string} source
 * @returns {{ importLine: string, field: string }}
 */
export function resolveHookBinding(key, rel, source) {
  const { hasDefault, named, hasStarExport } = scanModuleExports(source)
  const id = `hook_${key}`

  if (hasDefault) {
    return {
      importLine: `import ${id} from './${rel}'`,
      field: `  ${key}: ${id},`,
    }
  }

  if (named.includes(key)) {
    return {
      importLine: `import { ${key} as ${id} } from './${rel}'`,
      field: `  ${key}: ${id},`,
    }
  }

  if (named.length === 1 && !hasStarExport) {
    return {
      importLine: `import { ${named[0]} as ${id} } from './${rel}'`,
      field: `  ${key}: ${id},`,
    }
  }

  if (named.length > 1 || hasStarExport) {
    return {
      importLine: `import * as ${id} from './${rel}'`,
      field: `  ${key}: ${id},`,
    }
  }

  return {
    importLine: `import './${rel}'`,
    field: `  ${key}: true,`,
  }
}

function buildHydrateHelpers(moduleName) {
  return `
const vueFiles = import.meta.glob('./**/*.vue')

function globKeyFromComponent(comp) {
  if (typeof comp !== 'string') {
    return ''
  }
  const prefix = ${JSON.stringify(`@/modules/${moduleName}/`)}
  let rel = comp
  if (rel.startsWith(prefix)) {
    rel = rel.slice(prefix.length)
  }
  if (rel.startsWith('client/')) {
    rel = rel.slice('client/'.length)
  }
  if (!rel.startsWith('./')) {
    rel = \`./\${rel}\`
  }
  return rel
}

function hydrateComponent(comp) {
  if (typeof comp === 'function') {
    return comp
  }
  const key = globKeyFromComponent(comp)
  return key ? vueFiles[key] : comp
}

function hydrateRoute(route) {
  if (!route || typeof route !== 'object') {
    return route
  }
  const next = { ...route, component: hydrateComponent(route.component) }
  if (route.children && typeof route.children === 'object') {
    if (Array.isArray(route.children)) {
      next.children = route.children.map((child) => hydrateRoute(child))
    } else {
      next.children = Object.fromEntries(
        Object.entries(route.children).map(([name, child]) => [name, hydrateRoute(child)]),
      )
    }
  }
  return next
}

function hydrateRoutes(routes) {
  if (!routes || typeof routes !== 'object') {
    return routes
  }
  return Object.fromEntries(
    Object.entries(routes).map(([name, route]) => [name, hydrateRoute(route)]),
  )
}
`
}

function buildGeneratedSource({ moduleName, imports, fields, hasRoutes }) {
  const header = `/**
 * AUTO-GENERATED by generate-federation-entry.js — do not edit.
 */
${imports.join('\n')}
`
  if (!hasRoutes) {
    return `${header}
export default {
${fields.join('\n')}
}
`
  }

  return `${header}${buildHydrateHelpers(moduleName)}
const raw = {
${fields.join('\n')}
}

export default {
  ...raw,
  routes: hydrateRoutes(raw.routes),
}
`
}

/**
 * @param {string} moduleName
 * @param {string} moduleClientRoot
 * @returns {string} путь к entry (свой federation-entry.js или сгенерированный)
 */
export function ensureFederationEntry(moduleName, moduleClientRoot) {
  const own = path.join(moduleClientRoot, 'federation-entry.js')
  if (fs.existsSync(own)) {
    return own
  }

  const imports = []
  const fields = [`  moduleKey: ${JSON.stringify(moduleName)},`]
  let hasRoutes = false
  for (const [key, rel] of HOOKS) {
    const abs = path.join(moduleClientRoot, rel)
    if (!fs.existsSync(abs)) {
      continue
    }
    const binding = resolveHookBinding(key, rel, fs.readFileSync(abs, 'utf8'))
    imports.push(binding.importLine)
    fields.push(binding.field)
    if (key === 'routes') {
      hasRoutes = true
    }
  }

  const dest = generatedFederationEntryPath(moduleClientRoot)
  fs.writeFileSync(
    dest,
    buildGeneratedSource({ moduleName, imports, fields, hasRoutes }),
    'utf8',
  )
  return dest
}

export function removeGeneratedFederationEntry(moduleClientRoot) {
  const dest = generatedFederationEntryPath(moduleClientRoot)
  if (fs.existsSync(dest)) {
    fs.unlinkSync(dest)
  }
}
